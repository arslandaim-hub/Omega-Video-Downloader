package com.arslandaim.omegavideodownloader

import android.content.Context
import android.net.Uri
import android.util.Log
import java.io.File
import java.io.FileOutputStream

object CookiesManager {
    private const val TAG = "CookiesManager"
    private const val COOKIES_FILE_NAME = "cookies.txt"

    fun getCookiesPath(context: Context): String? {
        val file = File(context.filesDir, COOKIES_FILE_NAME)
        return if (file.exists() && file.length() > 0) file.absolutePath else null
    }

    fun importCookies(context: Context, uri: Uri): Boolean {
        return try {
            context.contentResolver.openInputStream(uri)?.use { input ->
                val outputFile = File(context.filesDir, COOKIES_FILE_NAME)
                FileOutputStream(outputFile).use { output ->
                    input.copyTo(output)
                }
            } != null
        } catch (e: Exception) {
            Log.e(TAG, "Failed to import cookies", e)
            false
        }
    }

    fun clearCookies(context: Context) {
        val file = File(context.filesDir, COOKIES_FILE_NAME)
        if (file.exists()) file.delete()
    }

    /**
     * Merges cookies for [domain] into Netscape cookies.txt, deduplicating by (domain, name)
     * so repeated saves never bloat the file with stale entries.
     */
    @Synchronized
    fun saveCookies(context: Context, cookies: String, domain: String) {
        saveCookiesForDomains(context, cookies, listOf(domain))
    }

    /**
     * Merges cookies into Netscape cookies.txt across one or more [domains] (e.g. `.x.com` and `.twitter.com`).
     * Uses a 1-year future expiration so `yt-dlp` / `MozillaCookieJar` never discards session cookies.
     */
    @Synchronized
    fun saveCookiesForDomains(context: Context, cookies: String, domains: List<String>) {
        try {
            val file = File(context.filesDir, COOKIES_FILE_NAME)
            val entries = LinkedHashMap<Pair<String, String>, String>()

            if (file.exists()) {
                file.readLines().forEach { line ->
                    if (line.isNotBlank() && !line.startsWith("#")) {
                        val cols = line.split('\t')
                        if (cols.size >= 7) {
                            entries[cols[0] to cols[5]] = line
                        }
                    }
                }
            }

            val expiry = (System.currentTimeMillis() / 1000L) + 31_536_000L
            for (domain in domains) {
                val domainWithDot = if (domain.startsWith(".")) domain else ".$domain"
                cookies.split(";").forEach { rawPair ->
                    val pair = rawPair.trim()
                    if (pair.isBlank()) return@forEach
                    val parts = pair.split("=", limit = 2)
                    if (parts.size == 2) {
                        val name = parts[0].trim()
                        val value = parts[1].trim()
                        if (name.isNotEmpty() && value.isNotEmpty()) {
                            entries[domainWithDot to name] =
                                "$domainWithDot\tTRUE\t/\tTRUE\t$expiry\t$name\t$value"
                        }
                    }
                }
            }

            val content = buildString {
                appendLine("# Netscape HTTP Cookie File")
                appendLine("# Generated by Omega Video Downloader")
                appendLine()
                entries.values.forEach { appendLine(it) }
            }
            file.writeText(content)
        } catch (e: Exception) {
            Log.e(TAG, "Failed to save cookies", e)
        }
    }

    /** True when `cookies.txt` contains an X/Twitter `auth_token` cookie. */
    fun hasTwitterAuthCookies(context: Context): Boolean {
        val file = File(context.filesDir, COOKIES_FILE_NAME)
        if (!file.exists() || file.length() == 0L) return false
        return try {
            file.readLines().any { line ->
                if (line.isBlank() || line.startsWith("#")) return@any false
                val cols = line.split('\t')
                cols.size >= 7 &&
                    (cols[0].contains("twitter.com", true) || cols[0].contains("x.com", true)) &&
                    cols[5] == "auth_token" &&
                    cols[6].isNotBlank()
            }
        } catch (_: Exception) {
            false
        }
    }
}
